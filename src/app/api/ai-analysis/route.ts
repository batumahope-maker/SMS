import { NextRequest, NextResponse } from 'next/server';
import { getServerSession } from 'next-auth';
import { authOptions } from '@/lib/auth';
import { demoData } from '@/lib/demo-data';
import { isDemoMode } from '@/lib/demo-mode';

function analysisFor(type: string, studentId: string | null, classId: string | null) {
  const student = demoData.aiData.students.find((item) => item.id === studentId) ?? null;
  const klass = demoData.aiData.classes.find((item) => item.id === classId) ?? null;

  switch (type) {
    case 'student':
      return {
        analysis: `Synthetic AI analysis for ${student?.fullName ?? 'the selected student'}. This is demo content and is not generated by a real model.`,
        stats: {
          'Average grade': '82%',
          'Pass rate': '100%',
          Strengths: 'Introduction to ICT',
          Recommendations: 'Review Mathematics, continue strong ICT practice.',
        },
      };
    case 'class':
      return {
        analysis: `Synthetic AI analysis for ${klass?.name ?? 'the selected class'}. This is demo content and is not generated by a real model.`,
        stats: {
          'Total students': demoData.aiData.classICT.totalStudents,
          'Average grade': `${demoData.aiData.classICT.averageGrade}%`,
          'Strong students': demoData.aiData.classICT.strong,
          'At-risk students': demoData.aiData.classICT.atRisk,
        },
      };
    default:
      return {
        analysis: `Synthetic AI analysis for ${demoData.aiData.school.name}. This is demo content and is not generated by a real model.`,
        stats: {
          Students: demoData.aiData.school.totalStudents,
          'Average grade': `${demoData.aiData.school.averageGrade}%`,
          'Pass rate': `${demoData.aiData.school.passRate}%`,
          'Weak students': demoData.aiData.school.weakStudents,
          'Overdue fees': demoData.aiData.school.overdueFees,
        },
      };
  }
}

export async function GET() {
  if (!isDemoMode()) return NextResponse.json({ error: 'Not available' }, { status: 501 });
  const session = await getServerSession(authOptions);
  if (!session || session.user.role !== 'admin') return NextResponse.json({ error: 'Unauthorized' }, { status: 401 });
  return NextResponse.json(analysisFor('school', null, null));
}

export async function POST(request: NextRequest) {
  if (!isDemoMode()) return NextResponse.json({ error: 'Not available' }, { status: 501 });
  const session = await getServerSession(authOptions);
  if (!session || session.user.role !== 'admin') return NextResponse.json({ error: 'Unauthorized' }, { status: 401 });

  try {
    const body = await request.json() as { type?: unknown; studentId?: unknown; classId?: unknown };
    const type = String(body.type ?? 'school');
    const result = analysisFor(
      type === 'student' || type === 'class' ? type : 'school',
      typeof body.studentId === 'string' ? body.studentId : null,
      typeof body.classId === 'string' ? body.classId : null
    );
    return NextResponse.json(result);
  } catch (error) {
    console.error('Error running demo AI analysis:', error);
    return NextResponse.json({ error: 'Analysis failed.' }, { status: 500 });
  }
}
